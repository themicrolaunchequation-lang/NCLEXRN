// ---------- helpers (k supplies unique gradient ids per scene) ----------
export function mk() {
  let n = 0; const defs = [];
  const g = (c1, c2) => { const id = 'g' + (++n); defs.push(`<linearGradient id="${id}" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="${c1}"/><stop offset="1" stop-color="${c2}"/></linearGradient>`); return `url(#${id})`; };
  const rg = (c1, c2, cx = .35, cy = .3, r = .8) => { const id = 'g' + (++n); defs.push(`<radialGradient id="${id}" cx="${cx}" cy="${cy}" r="${r}"><stop offset="0" stop-color="${c1}"/><stop offset="1" stop-color="${c2}"/></radialGradient>`); return `url(#${id})`; };
  return { g, rg, defs };
}
const glossy = (inner) => `<g filter="url(#gl)">${inner}</g>`;
const sh = (cx, cy, rx, ry = rx * .2) => `<ellipse cx="${cx}" cy="${cy}" rx="${rx}" ry="${ry}" fill="#1b2a3a" opacity=".2" filter="url(#bl)"/>`;
const hl = (cx, cy, rx, ry, rot = -30, o = .45) => `<ellipse cx="${cx}" cy="${cy}" rx="${rx}" ry="${ry}" transform="rotate(${rot} ${cx} ${cy})" fill="#fff" opacity="${o}" filter="url(#bl2)"/>`;
const path = (d, fill, stroke = 'none', sw = 0, extra = '') => `<path d="${d}" fill="${fill}" stroke="${stroke}" stroke-width="${sw}" stroke-linecap="round" stroke-linejoin="round" ${extra}/>`;
const line = (d, c, w, o = 1) => `<path d="${d}" fill="none" stroke="${c}" stroke-width="${w}" stroke-linecap="round" stroke-linejoin="round" opacity="${o}"/>`;
const circ = (cx, cy, r, fill, extra = '') => `<circle cx="${cx}" cy="${cy}" r="${r}" fill="${fill}" ${extra}/>`;
const rect = (x, y, w, h, r, fill, extra = '') => `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${r}" fill="${fill}" ${extra}/>`;
const T = (x, y, s, inner, rot = 0) => `<g transform="translate(${x} ${y}) rotate(${rot}) scale(${s})">${inner}</g>`;
const SKIN = (k) => k.g('#f6c6a2', '#d99468');

